"""All Aspect-1 analyses from diagnostics + training logs -> results/.

  python scripts/analyze.py            # uses diag/ and runs/
Outputs: results/*.csv, results/figures/*.png, results/summary.json, results/REPORT.md
"""
import argparse
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from rlaif.analysis import hazard, plots, stopping  # noqa: E402
from rlaif.analysis.events import DEFINITIONS, collapse_onset, error_concentration, load_run, online_youden, problem_events, run_curves  # noqa: E402

ARM_LABEL = {"train": "full pool", "drop_lowver": "drop least-verifiable", "drop_gap": "drop largest solve gap", "drop_random": "drop random"}


def fmt(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


INT_COLS = {"steps", "folds", "n_units", "n_events", "collapse_onset", "outsolve_step", "stop_step", "ckpt_step", "n_runs"}


def md_table(df, cols=None, nd=3):
    if df is None or len(df) == 0:
        return "_(no data yet)_\n"
    df = df[cols] if cols else df
    head = "| " + " | ".join(str(c) for c in df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    rows = []
    for _, r in df.iterrows():
        cells = []
        for c, v in zip(df.columns, r.values):
            if c == "lr" and isinstance(v, (float, np.floating)):
                cells.append(f"{v:.0e}")
                continue
            if c in INT_COLS and isinstance(v, (float, np.floating)) and not np.isnan(v):
                cells.append(str(int(v)))
            else:
                cells.append(fmt(v, nd) if isinstance(v, (float, np.floating)) else str(v))
        rows.append("| " + " | ".join(cells) + " |")
    return head + "\n".join(rows) + "\n"


def write_report(out, figs_rel="figures"):
    """Auto-generated tables + figures. Interpretation lives in results/FINDINGS.md (written by hand)."""
    def load(name):
        p = os.path.join(out, name)
        return pd.read_csv(p) if os.path.exists(p) else None

    L = ["# Aspect 1 (RLAIF reliability): results\n", "_Auto-generated by `scripts/analyze.py`; see `FINDINGS.md` for the interpretation._\n"]
    L += ["## 1. Pre-training audit: global judge quality\n", "Natural base-policy samples, verdict = P(Yes) > 0.5. `fp_share_low_tercile`: share of all false accepts that fall on the least-verifiable third of problems.\n",
          md_table(load("diag_global.csv"), ["task", "judge", "mode", "tpr", "fpr", "youden", "base_gold", "judge_solve", "fp_share_low_tercile", "frac_problems_neg_youden"])]
    L += ["\n![](%s/diag_countdown_gap_vs_youden.png) ![](%s/diag_math_gap_vs_youden.png)\n" % (figs_rel, figs_rel)]
    L += ["## 2. GRPO runs\n", md_table(load("runs_summary.csv"), ["run", "task", "lr", "steps", "heldout_gold_0", "heldout_gold_peak", "heldout_gold_final", "train_fp_first16", "train_fp_last16", "collapse_onset", "pretrain_global_youden", "online_youden_at_onset", "outsolve_step"])]
    L += ["\n### Run level: pre-training judge statistics vs outcome\n", "`planted_wrong_accept`: how often the judge accepts a planted wrong answer that claims to be right; `delta_heldout_gold`: final - initial held-out gold accuracy.\n",
          md_table(load("run_level.csv"), ["run", "task", "global_youden", "mean_youden", "mean_auroc", "mean_bon_fool_16", "planted_wrong_accept", "mean_solve_gap", "delta_heldout_gold", "collapse_onset"])]
    for t in ("countdown", "math"):
        for m in ("standard", "commit_first"):
            L.append(f"\n![]({figs_rel}/train_{t}_{m}.png)\n")
        L.append(f"\n![]({figs_rel}/online_youden_{t}_standard.png) ![]({figs_rel}/concentration_{t}.png)\n")
    L += ["## 3. Predicting per-problem exploitation onset\n", "Univariate C-index of each pre-training feature (risk direction in parentheses):\n", md_table(load("hazard_univariate_cindex.csv")),
          "\nDiscrete-time hazard model, out-of-sample:\n", md_table(load("hazard_heldout_summary.csv")), f"\n![]({figs_rel}/hazard_cindex.png)\n\n![]({figs_rel}/km_terciles.png)\n",
          "\n### Alternative event definitions\n", "**fooled** (judge accepts most of a visit's wrong answers) - univariate C and held-out hazard model:\n", md_table(load("hazard_univariate_cindex_fooled.csv")), md_table(load("hazard_heldout_summary_fooled.csv")),
          "\n**unlearned** (gold accuracy falls 0.25 below base while the judge accepts):\n", md_table(load("hazard_univariate_cindex_unlearned.csv")), md_table(load("hazard_heldout_summary_unlearned.csv")),
          "\n### Slower learning rate (lr 1e-5) runs only\n", md_table(load("hazard_univariate_cindex_slow.csv")), md_table(load("hazard_heldout_summary_slow.csv")), f"\n![]({figs_rel}/train_countdown_slow_lr.png)\n"]
    L += ["## 4. Causal test (remove 25% of the pool)\n", md_table(load("causal_arms.csv"), ["task", "arm", "heldout_gold_0", "heldout_gold_peak", "heldout_gold_final", "train_fp_first16", "train_fp_last16", "collapse_onset"]) if load("causal_arms.csv") is not None else "_(no data yet)_\n"]
    for t in ("countdown", "math"):
        L.append(f"\n![]({figs_rel}/causal_{t}.png)\n")
    L += ["## 5. Commit-first vs standard judging\n", md_table(load("commit_first_vs_standard.csv"))]
    L += ["\n### Do exploits transfer across judges?\n", "Rollouts from the first and last epoch of each standard run, re-scored by every judge (`scripts/cross_judge.py`).\n"]
    for t in ("countdown", "math"):
        L += [f"\n**{t}**\n", md_table(load(f"cross_judge_{t}.csv"))]
    L += ["## 6. Label-free early stopping (thresholds tuned on the other task)\n", md_table(load("early_stopping.csv"))]
    with open(os.path.join(out, "REPORT.md"), "w") as fh:
        fh.write("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--diag_dir", default="diag")
    ap.add_argument("--runs_dir", default="runs")
    ap.add_argument("--out", default="results")
    ap.add_argument("--tau", type=float, default=0.5)
    a = ap.parse_args()
    figs = os.path.join(a.out, "figures")
    os.makedirs(figs, exist_ok=True)
    S = {}  # summary

    # ---------------- diagnostics ----------------
    feats = pd.concat([pd.read_csv(p) for p in glob.glob(os.path.join(a.diag_dir, "*", "features.csv"))], ignore_index=True)
    glob_v = pd.concat([pd.read_csv(p) for p in glob.glob(os.path.join(a.diag_dir, "*", "global.csv"))], ignore_index=True)
    glob_v.to_csv(os.path.join(a.out, "diag_global.csv"), index=False)
    S["diag_global"] = glob_v.to_dict("records")
    corr = []
    for (t, j, m), d in feats.groupby(["task", "judge", "mode"]):
        corr.append({"task": t, "judge": j, "mode": m, "spearman(youden, solve_gap)": d[["youden", "solve_gap"]].corr("spearman").iloc[0, 1], "spearman(youden, bon_fool_16)": d[["youden", "bon_fool_16"]].corr("spearman").iloc[0, 1]})
    pd.DataFrame(corr).to_csv(os.path.join(a.out, "diag_feature_correlations.csv"), index=False)
    for t in feats.task.unique():
        f = feats[(feats.task == t) & (feats["mode"] == "standard")]
        plots.scatter_features(f, "solve_gap", "youden", os.path.join(figs, f"diag_{t}_gap_vs_youden.png"), f"{t}: verifiability vs solve gap (pre-training)", "solve gap (policy - judge solve rate)", "per-problem Youden J")

    # ---------------- runs ----------------
    all_runs = [r for r in (load_run(d) for d in sorted(glob.glob(os.path.join(a.runs_dir, "*", "*")))) if r is not None]
    base_lr = max(r["lr"] for r in all_runs) if all_runs else 0.0
    runs = [r for r in all_runs if r["lr"] == base_lr]  # main grid; slower-lr variants are analysed separately
    slow = [r for r in all_runs if r["lr"] < base_lr]
    print(f"{len(runs)} main runs (lr={base_lr}), {len(slow)} slow-lr runs")
    run_rows = []
    for r in all_runs:
        ev = r["evals"]
        onset = collapse_onset(r)
        gv = glob_v[(glob_v.task == r["task"]) & (glob_v.judge == r["judge"]) & (glob_v["mode"] == r["mode"])]
        oy = online_youden(r)
        oy_at = oy[oy.step >= onset].iloc[0]["youden"] if onset is not None and (oy.step >= onset).any() else np.nan
        # step where the policy first out-solves its judge on the training pool (EMA of train gold acc > judge mean solve rate)
        c = run_curves(r)
        js = gv["judge_solve"].iloc[0] if len(gv) else np.nan
        outsolve = c.step[c.gold_acc_ema > js]
        run_rows.append({
            "run": r["name"], "task": r["task"], "judge": r["judge"], "mode": r["mode"], "pool": r["pool"], "lr": r["lr"], "seed": r["seed"], "steps": int(r["steps"].step.max()) + 1, "done": r["done"],
            "heldout_gold_0": float(ev.gold_acc.iloc[0]) if len(ev) else np.nan,
            "heldout_gold_peak": float(ev.gold_acc.max()) if len(ev) else np.nan,
            "heldout_gold_final": float(ev.gold_acc.iloc[-1]) if len(ev) else np.nan,
            "heldout_accept_final": float(ev.judge_accept.iloc[-1]) if len(ev) else np.nan,
            "train_fp_first16": float(r["steps"].fp_rate.iloc[:16].mean()), "train_fp_last16": float(r["steps"].fp_rate.iloc[-16:].mean()),
            "collapse_onset": onset, "pretrain_global_youden": float(gv.youden.iloc[0]) if len(gv) else np.nan, "online_youden_at_onset": oy_at,
            "judge_mean_solve": js, "outsolve_step": int(outsolve.iloc[0]) if len(outsolve) else None,
        })
    run_df = pd.DataFrame(run_rows)
    run_df.to_csv(os.path.join(a.out, "runs_summary.csv"), index=False)
    S["runs"] = run_df.to_dict("records")

    # run level: pre-training judge statistics (averaged over the run's problems) vs what training did
    lvl = []
    for r in all_runs:
        f = feats[(feats.task == r["task"]) & (feats.judge == r["judge"]) & (feats["mode"] == r["mode"]) & feats.pid.isin(r["roll"]["pid"].unique())]
        row = run_df[run_df.run == r["name"]].iloc[0]
        lvl.append({
            "run": r["name"], "task": r["task"], "judge": r["judge"], "mode": r["mode"], "pool": r["pool"], "lr": r["lr"],
            "global_youden": row["pretrain_global_youden"], "mean_youden": f.youden.mean(), "mean_auroc": f.auroc.mean(),
            "mean_bon_fool_16": f.bon_fool_16.mean(), "planted_wrong_accept": f.syn_neg_accept.mean(), "mean_solve_gap": f.solve_gap.mean(),
            "delta_heldout_gold": row["heldout_gold_final"] - row["heldout_gold_0"], "collapse_onset": row["collapse_onset"],
        })
    lvl = pd.DataFrame(lvl)
    lvl.to_csv(os.path.join(a.out, "run_level.csv"), index=False)
    S["run_level"] = lvl.to_dict("records")

    # training curves per task (standard judges, full pool) + commit-first overlay
    for t in sorted({r["task"] for r in runs}):
        for mode in ("standard", "commit_first"):
            sel = [r for r in runs if r["task"] == t and r["mode"] == mode and r["pool"] == "train"]
            if sel:
                sel = [r for r in sel if r["seed"] == 0]  # seed replicates are summarised in the runs table
                plots.training_curves([(r["judge"], plots.judge_color(r["judge"]), run_curves(r), r["evals"], collapse_onset(r)) for r in sorted(sel, key=lambda r: plots.JUDGE_ORDER.index(r["judge"]))], os.path.join(figs, f"train_{t}_{mode}.png"), f"{t}: GRPO against frozen {mode.replace('_', '-')} judges")
                plots.online_youden([(r["judge"], plots.judge_color(r["judge"]), online_youden(r), collapse_onset(r)) for r in sel], os.path.join(figs, f"online_youden_{t}_{mode}.png"), f"{t}: global judge Youden on current rollouts ({mode})")

    # ---------------- per-problem events + hazard model ----------------
    defs = {}
    for definition in DEFINITIONS:
        u = pd.concat([problem_events(r, feats, tau=a.tau, definition=definition) for r in all_runs], ignore_index=True) if all_runs else pd.DataFrame()
        defs[definition] = u
        if len(u) and definition != "exploited":
            ru = u[u.at_risk & (u["mode"] == "standard")].reset_index(drop=True)
            if ru.event.sum() >= 5:
                uc = hazard.univariate_c(ru, ["youden", "bon_fool_16", "solve_gap", "policy_solve", "judge_solve", "base_fp", "auroc"], {"youden": -1, "auroc": -1, "policy_solve": -1, "judge_solve": -1})
                uc.to_csv(os.path.join(a.out, f"hazard_univariate_cindex_{definition}.csv"), index=False)
                hr = hazard.evaluate_feature_sets(ru)
                hr.groupby(["split", "features"]).apply(lambda d: pd.Series({"c_index": np.average(d.c_index, weights=d.n_events), "auc_rows": np.nanmean(d.auc_rows), "folds": len(d)})).reset_index().to_csv(os.path.join(a.out, f"hazard_heldout_summary_{definition}.csv"), index=False)
                S[f"events_{definition}"] = {"n_at_risk_standard": int(len(ru)), "n_events_standard": int(ru.event.sum())}
    units = defs["exploited"]
    if len(units):
        units.drop(columns=["visit_steps"]).to_csv(os.path.join(a.out, "problem_events.csv"), index=False)
        risk_units = units[units.at_risk & (units["mode"] == "standard")].reset_index(drop=True)
        S["events"] = {"n_units": int(len(units)), "n_at_risk_standard": int(len(risk_units)), "n_events_standard": int(risk_units.event.sum())}
        uni = hazard.univariate_c(risk_units, ["youden", "youden_nat", "bon_fool_16", "bon_fool_4", "solve_gap", "policy_solve", "judge_solve", "base_fp", "syn_neg_accept", "auroc"], {"youden": -1, "youden_nat": -1, "auroc": -1, "policy_solve": -1, "judge_solve": -1})
        uni.to_csv(os.path.join(a.out, "hazard_univariate_cindex.csv"), index=False)
        S["univariate_c"] = uni.to_dict("records")
        if risk_units.event.sum() >= 5:
            res = hazard.evaluate_feature_sets(risk_units)
            res.to_csv(os.path.join(a.out, "hazard_heldout.csv"), index=False)
            agg = res.groupby(["split", "features"]).apply(lambda d: pd.Series({"c_index": np.average(d.c_index, weights=d.n_events), "nll_per_row": np.average(d.nll_per_row, weights=d.n_units), "auc_rows": np.nanmean(d.auc_rows), "auc_ever": np.nanmean(d.auc_ever), "folds": len(d)})).reset_index()
            agg.to_csv(os.path.join(a.out, "hazard_heldout_summary.csv"), index=False)
            S["hazard"] = agg.to_dict("records")
            plots.cindex_bars(agg, os.path.join(figs, "hazard_cindex.png"), "Predicting per-problem exploitation onset (held-out)")
            ra = hazard.oof_risk(risk_units, hazard.FEATURE_SETS["verifiability"])
            rb = hazard.oof_risk(risk_units, hazard.FEATURE_SETS["solve gap"])
            d, lo, hi = hazard.bootstrap_delta_c(risk_units, ra, rb)
            S["delta_c_verif_minus_gap_heldout_problems"] = {"delta": d, "lo": lo, "hi": hi}
            full = hazard.HazardModel(hazard.FEATURE_SETS["verifiability + solve"]).fit(hazard.person_period(risk_units))
            S["hazard_coefficients_std"] = full.coefficients()
        # Kaplan-Meier by terciles
        su = risk_units[risk_units.run.isin({r["name"] for r in slow})].reset_index(drop=True)
        if su.event.sum() >= 5 and su.pid.nunique() >= 10:
            sres = hazard.evaluate_feature_sets(su, splits=("heldout_problems",))
            sres.groupby(["split", "features"]).apply(lambda d: pd.Series({"c_index": np.average(d.c_index, weights=d.n_events), "auc_rows": np.nanmean(d.auc_rows), "folds": len(d)})).reset_index().to_csv(os.path.join(a.out, "hazard_heldout_summary_slow.csv"), index=False)
            hazard.univariate_c(su, ["youden", "bon_fool_16", "solve_gap", "policy_solve", "judge_solve", "base_fp"], {"youden": -1, "policy_solve": -1, "judge_solve": -1}).to_csv(os.path.join(a.out, "hazard_univariate_cindex_slow.csv"), index=False)
        km_sets = []
        for col, name, asc in (("youden", "pre-training Youden J", True), ("solve_gap", "solve gap", False)):
            q = risk_units[col].rank(pct=True, method="first")
            groups = [("lowest third", q <= 1 / 3), ("middle third", (q > 1 / 3) & (q <= 2 / 3)), ("highest third", q > 2 / 3)]
            vmax = int(risk_units["T"].max())
            km_sets.append((f"by {name}", [(lab, plots.SERIES[k], hazard.kaplan_meier(risk_units[m], vmax)) for k, (lab, m) in enumerate(groups)]))
        plots.km_by_tercile(km_sets, os.path.join(figs, "km_terciles.png"), "Per-problem survival against exploitation (standard judges)")

    for t in sorted({r["task"] for r in slow}):
        sel = [r for r in slow if r["task"] == t] + [r for r in runs if r["task"] == t and r["mode"] == "standard" and r["pool"] == "train" and r["judge"] in {x["judge"] for x in slow}]
        lab = lambda r: f"{r['judge']} lr={r['lr']:.0e}"
        plots.training_curves([(lab(r), plots.SERIES[k], run_curves(r), r["evals"], collapse_onset(r)) for k, r in enumerate(sorted(sel, key=lab))], os.path.join(figs, f"train_{t}_slow_lr.png"), f"{t}: slower learning rate")

    # ---------------- error concentration ----------------
    conc_rows = []
    for r in runs:
        ec = error_concentration(r, feats)
        ec["run"] = r["name"]
        conc_rows.append(ec)
    if conc_rows:
        pd.concat(conc_rows).to_csv(os.path.join(a.out, "error_concentration.csv"), index=False)
        for t in sorted({r["task"] for r in runs}):
            sel = [(r, c) for r, c in zip(runs, conc_rows) if r["task"] == t and r["mode"] == "standard" and r["pool"] == "train"]
            if sel:
                plots.concentration_curves([(r["judge"], plots.judge_color(r["judge"]), c) for r, c in sorted(sel, key=lambda x: plots.JUDGE_ORDER.index(x[0]["judge"]))], os.path.join(figs, f"concentration_{t}.png"), f"{t}: errors on the least-verifiable third")

    # ---------------- causal test ----------------
    causal = []
    for t in sorted({r["task"] for r in runs}):
        arms = [r for r in runs if r["task"] == t and r["mode"] == "standard" and r["pool"].startswith("drop_")]
        if not arms:
            continue
        j = arms[0]["judge"]
        full = [r for r in runs if r["task"] == t and r["mode"] == "standard" and r["pool"] == "train" and r["judge"] == j and r["seed"] == 0]
        sel = full + sorted(arms, key=lambda r: r["pool"])
        plots.arm_curves([(ARM_LABEL.get(r["pool"], r["pool"]), plots.SERIES[k], run_curves(r), r["evals"]) for k, r in enumerate(sel)], os.path.join(figs, f"causal_{t}.png"), f"{t}: causal test with judge {j}")
        for r in sel:
            row = run_df[run_df.run == r["name"]].iloc[0].to_dict()
            row["arm"] = r["pool"]
            # exploitation on the problems all arms share
            causal.append(row)
    if causal:
        cdf = pd.DataFrame(causal)
        cdf.to_csv(os.path.join(a.out, "causal_arms.csv"), index=False)
        S["causal"] = cdf.to_dict("records")

    # ---------------- commit-first vs standard ----------------
    cf = run_df[(run_df.pool == "train") & (run_df.seed == 0) & (run_df.lr == base_lr)].pivot_table(index=["task", "judge"], columns="mode", values=["heldout_gold_final", "heldout_gold_peak", "train_fp_last16", "collapse_onset", "pretrain_global_youden"], aggfunc="first")
    if len(cf):
        cf.columns = [f"{a_}|{b_}" for a_, b_ in cf.columns]
        cf.reset_index().to_csv(os.path.join(a.out, "commit_first_vs_standard.csv"), index=False)
        S["commit_first"] = cf.reset_index().to_dict("records")

    # ---------------- label-free early stopping ----------------
    done_runs = [r for r in runs if len(r["evals"]) >= 3]
    if done_runs:
        tab, grid = stopping.cross_task_stopping(done_runs, feats)
        tab.to_csv(os.path.join(a.out, "early_stopping.csv"), index=False)
        grid.to_csv(os.path.join(a.out, "early_stopping_grid.csv"), index=False)
        S["early_stopping"] = tab.to_dict("records")

    write_report(a.out)
    with open(os.path.join(a.out, "summary.json"), "w") as fh:
        json.dump(S, fh, indent=2, default=lambda o: None if (isinstance(o, float) and np.isnan(o)) else (o.item() if hasattr(o, "item") else str(o)))
    print(json.dumps({k: v for k, v in S.items() if k in ("events", "delta_c_verif_minus_gap_heldout_problems")}, indent=2, default=str))


if __name__ == "__main__":
    main()
